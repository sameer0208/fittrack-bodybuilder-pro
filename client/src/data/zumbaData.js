// ─── Utilities ───────────────────────────────────────────────────────────────
export function getMoveById(id) {
  return ZUMBA_MOVES.find((m) => m.id === id);
}

export function getSessionWithMoves(sessionId) {
  const session = ZUMBA_SESSIONS.find((s) => s.id === sessionId);
  if (!session) return null;
  return {
    ...session,
    movesDetailed: session.moves.map((m) => ({
      ...getMoveById(m.moveId),
      sessionDuration: m.duration,
    })),
  };
}

export function formatDuration(totalSec) {
  const m = Math.floor(totalSec / 60);
  const s = totalSec % 60;
  return s > 0 ? `${m}m ${s}s` : `${m}m`;
}

